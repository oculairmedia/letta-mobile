package com.letta.mobile.robolectric

import java.util.Properties
import org.gradle.api.DefaultTask
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault

/**
 * Writes the `robolectric-deps.properties` file Robolectric reads (see [RobolectricDepsPlugin]): one
 * `group:artifact:version=/absolute/path.jar` line per resolved jar.
 */
@DisableCachingByDefault(because = "The output holds absolute paths into the local Gradle cache.")
abstract class WriteRobolectricDepsTask : DefaultTask() {
    /** Maven coordinate (`group:artifact:version`) to the absolute path of the resolved jar. */
    @get:Input
    abstract val artifacts: MapProperty<String, String>

    @get:OutputFile
    abstract val propertiesFile: RegularFileProperty

    @TaskAction
    fun write() {
        val properties = Properties().apply { artifacts.get().toSortedMap().forEach { (key, value) -> setProperty(key, value) } }
        val file = propertiesFile.get().asFile
        file.parentFile.mkdirs()
        file.outputStream().use { properties.store(it, "Generated by writeRobolectricDeps; do not edit.") }
    }
}
